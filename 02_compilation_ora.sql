CREATE OR REPLACE FUNCTION fn_compilation RETURN varchar2
AS
	v_int integer;
	v_bool boolean := false;
BEGIN
	NULL;
	-- Каждая из этих ошибок приведет к инвалидному состоянию функции:
	--------------------------------------------------------------------------------
	
	-- Проблемы с объектами: PL/SQL: ORA-00942: таблица или представление пользователя не существует
	update unknow_table SET col1 = 'a';
	
	-- Синтаксис: PLS-00103: Встретился символ "=" в то время как ожидалось одно из следующих:
	var = 1;
	
	-- Типы данных: PLS-00382: выражение неправильного типа
	v_int := v_bool;

	
	-- А эти ошибки компилятор не заметит. Они возникнут только на этапе выполнения:
	--------------------------------------------------------------------------------
	-- Компилятор посчитал, что возможно успешное неявное преобразование типов. Но:
	-- ORA-06502: PL/SQL: : ошибка преобразования символа в число ошибка числа или значения
	v_int := 'zxsdgfbsfhbg';
	
    -- Отсутствие RETURN
	-- ORA-06503: PL/SQL: Возврат функции без значения 
END;
/

-- Инвалидные объекты можно увидеть через представления ALL_OBJECTS/DBA_OBJECTS 
SELECT * FROM all_objects WHERE status <> 'VALID';


-- Инвалидной процедура (функция/пакет) может стать не только из-за ошибки при очередной компиляции, но и в следствие изменения связанного объекта.
-- При следующем запуске инвалидированной процедуры будет запущена ее автоматическая перекомпиляция, и если изменения объекта процедуру не сломали, то она упешно перекомпилится

CREATE TABLE referenced_table (col1 varchar2(255));


CREATE OR REPLACE FUNCTION fn_compilation2 RETURN varchar2
AS
	v_res referenced_table.col1%TYPE;
BEGIN
	SELECT max(col1) INTO v_res FROM referenced_table;
	RETURN v_res;
END;
/

-- Теперь меняем referenced_table
ALTER TABLE referenced_table MODIFY col1 varchar2(258);

-- И видим, что FN_COMPILATION2 стала инвалидной
SELECT * FROM all_objects WHERE status <> 'VALID';

-- Выполняем ее и видим, что она успешно перекомпилилась и опять стала валидной
SELECT fn_compilation2 FROM dual;

-- Можно не дожидаться запуска процедуры, а запустить перекомпиляцию всех инвалидных объетов вручную
BEGIN 
	sys.UTL_RECOMP.RECOMP_PARALLEL(4); 
END;

-- После доработок объектов на базе обязательной практикой является проверка на наличие инвалидных объектов.
