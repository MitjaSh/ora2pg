-- Под суперпользователем (root)

CREATE TEMP TABLE my_temp_table (
    c1 VARCHAR(100)
) ON COMMIT PRESERVE ROWS; -- COMMIT DELETE ROWS / ON COMMIT DROP

-- Временные таблицы создаются специальных сессионных схемах вида pg_temp_N (где N — номер сеанса, например pg_temp_3).
SELECT 
    n.nspname AS schema_name,
    c.relname AS table_name
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE c.relname = 'my_temp_table';

-- Если создать временную таблицу с тем же именем, что и у постоянной таблицы, временная таблица временно «перекроет» постоянную в текущей сессии.
-- Обращения по имени без указания схемы будут идти именно к временной таблице, пока она не будет удалена.

-- Другие сессии не видят не только данные, но и саму таблицу тоже
-- Могут быть полезны для хранения промежуточных расчетов

-- Данные временных таблиц обрабатываются в локальном буфере процесса (temp_buffers), а не в общем пуле памяти (shared_buffers),
-- и для них не пишется WAL-журнал (аналог redo-логов), что делает работу с ними быстрой.